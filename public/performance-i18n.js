/**
 * Global translation lookup function
 */
function t(key, fallback = '') {
  const lang = window.currentSahlaLang || 'ar';
  return SAHLA_PERF_I18N[lang]?.[key] ?? SAHLA_PERF_I18N['en']?.[key] ?? fallback ?? key;
}

/**
 * Format status badge with localized label
 */
function localizedStatusLabel(status) {
  if (!status) return '—';
  const norm = String(status).toLowerCase().trim();
  const key = `status_${norm}`;
  return t(key, status);
}

/**
 * Set dashboard language, update DOM and persist in localStorage
 */
function setSahlaLanguage(lang, triggerRefresh = true) {
  if (!SAHLA_PERF_I18N[lang]) lang = 'ar';
  window.currentSahlaLang = lang;
  try {
    localStorage.setItem('sahla_perf_lang', lang);
  } catch (_) {}

  const isRtl = (lang === 'ar');
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', isRtl);

  // Update switcher active states
  document.querySelectorAll('.sahla-lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Apply all data-i18n attributes in DOM
  applyDomTranslations();

  // Trigger active panel refresh if app is loaded
  if (triggerRefresh && typeof refreshCurrentActiveView === 'function') {
    try {
      refreshCurrentActiveView();
    } catch (_) {}
  }
}

/**
 * Apply translation keys to DOM elements marked with data-i18n attributes
 */
function applyDomTranslations() {
  // Elements with inner text translation
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translated;
      } else {
        // Keep child badge elements intact if any
        const badge = el.querySelector('.tab-badge, .badge');
        if (badge) {
          const badgeClone = badge.cloneNode(true);
          const icon = el.querySelector('.tab-icon');
          el.innerHTML = (icon ? icon.outerHTML + ' ' : '') + translated;
          el.appendChild(badgeClone);
        } else {
          el.textContent = translated;
        }
      }
    }
  });

  // Elements with title tooltip translation
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    const translated = t(key);
    if (translated) el.title = translated;
  });

  // Elements with placeholder translation
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = t(key);
    if (translated) el.placeholder = translated;
  });
}

/**
 * Renders inline items summary badge with localized prefix and empty fallback
 */
function renderOrderSummaryInlineHtml(itemsSummary) {
  const prefix = typeof t === 'function' ? t('inline_items', 'Items: ') : 'Items: ';
  const fallback = typeof t === 'function' ? t('od_no_items', 'No items') : 'No items';
  const cleanSummary = (itemsSummary && String(itemsSummary).trim()) || fallback;
  const safePrefix = String(prefix ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const safeContent = String(cleanSummary).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  return '<span class="order-summary-inline">' + safePrefix + safeContent + '</span>';
}

/**
 * Generates empty table row with localized message
 */
function renderEmptyRow(colspan, customKeyOrText) {
  const text = (customKeyOrText && typeof t === 'function' && t(customKeyOrText))
    ? t(customKeyOrText)
    : (customKeyOrText || (typeof t === 'function' ? t('empty_none', 'None') : 'None'));
  const safeText = String(text ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  return '<tr><td colspan="' + colspan + '" class="meta">' + safeText + '</td></tr>';
}

/**
 * Triggers re-rendering of the currently active view/tab without reloading
 */
function refreshCurrentActiveView() {
  const activeTabBtn = document.querySelector('.tab[data-tab].active');
  const activeTab = activeTabBtn ? activeTabBtn.getAttribute('data-tab') : 'alerts';
  if (typeof selectTab === 'function') {
    selectTab(activeTab, { skipPersist: true });
  }
}

